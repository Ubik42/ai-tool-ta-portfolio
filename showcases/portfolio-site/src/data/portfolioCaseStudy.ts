function buildReviewerAcceptanceReport(): CaseStudyAcceptanceReport {
  const accepted = caseStudyAcceptanceItems.filter((item) => item.state === "accepted").length;
  const pending = caseStudyAcceptanceItems.filter((item) => item.state === "pending").length;
  const rework = caseStudyAcceptanceItems.filter((item) => item.state === "rework").length;
  const requiredPending = caseStudyAcceptanceItems.filter(
    (item) => item.required && item.state !== "accepted",
  ).length;
  const gate: CaseStudyGate = rework > 0 ? "Blocked" : requiredPending > 0 ? "Review" : "Ready";

  return {
    summary: {
      gate,
      total: caseStudyAcceptanceItems.length,
      accepted,
      pending,
      rework,
      requiredPending,
      nextAction:
        requiredPending > 0
          ? "Resolve R2 fixability receipt and R4 mutation-boundary receipt before marking the portfolio package Ready."
          : "All required case-study acceptances are recorded; package can move to public release hardening.",
    },
    items: caseStudyAcceptanceItems,
  };
}

